#!/usr/bin/env bash
# gen-extra-hosts.sh - emit the suite container's extra_hosts lines
# (auth DESIGN 9a.2 item 2c, RIGMODE-1).
#
# The suite container resolves the platform's auth hostnames with a
# docker-provided answer pinned to the host: the public wildcard dev
# zone inside a container resolves to the CONTAINER's own loopback, so
# every family env's auth host needs one "host:ip" mapping. The hosts are
# generated from the battery family table (conformance-seed-all.sh's
# FAMILY map - the single source of truth for env slugs) under the RIG
# MODE's domain (conformance/domain.env's SENTIN8_DOMAIN, then the
# tree-root .env's, then the local default) - no per-suffix hardcode
# remains.
#
# Usage:
#   bash conformance/gen-extra-hosts.sh              # HOSTIP= lines to stdout
#   bash conformance/gen-extra-hosts.sh --write      # rewrite extra_hosts.env
#
# docker-compose.yml includes extra_hosts:
#   - the literal local/auth.ops.sys lines (mode-independent loopback
#     defaults), and
#   - one ${HOST:-} interpolated line per family (from extra_hosts.env),
#     so a regenerated file lands on the next `docker compose up`
#     without editing the compose.
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"        # group repo (sentin8/)
TREE_ROOT="$(cd "$ROOT/.." && pwd)"      # tree root

DOMAIN=""
# The mode file: the GROUP root's conformance/domain.env (where the make
# targets write), then an in-repo copy, then the tree-root .env.
for MODE_FILE in "$ROOT/conformance/domain.env" "$HERE/domain.env"; do
  if [ -n "$DOMAIN" ]; then break; fi
  if [ -f "$MODE_FILE" ]; then
    # `|| true`: RIGMODE-3 requires the mode file to omit SENTIN8_DOMAIN, so
    # "no match" is the EXPECTED answer and must fall through to the tree
    # .env - not abort (this script runs without -e so it currently survives,
    # but the same line in conformance-seed.sh exits the script silently).
    DOMAIN="$(grep -m1 '^SENTIN8_DOMAIN=' "$MODE_FILE" | cut -d= -f2 | tr -d '"' | tr -d ' ' || true)"
  fi
done
if [ -z "$DOMAIN" ] && [ -f "$TREE_ROOT/.env" ]; then
  DOMAIN="$(grep -m1 '^SENTIN8_DOMAIN=' "$TREE_ROOT/.env" | cut -d= -f2 | tr -d '"' | tr -d ' ' || true)"
fi
DOMAIN="${DOMAIN:-local.sentin8.dev}"

# The IP the container must map the hosts to: the docker host gateway's
# IPv4 when unset (resolved by compose's `host-gateway`), else an
# operator override (DOCKER_HOST_IPV4). The compose line keeps the
# ${DOCKER_HOST_IPV4:-host-gateway} form, so this file carries only the
# HOSTNAME side of each mapping.
ORG_SLUG="conformance-local"
FAMILIES=(cert cert-fcl cert-imp cert-hyb cert-fp cert-sm cert-vp cert-f2m cert-fapi1 cert-fapi2 cert-ciba cert-vci cert-haip cert-wallet cert-vpw)

emit() {
  for slug in "${FAMILIES[@]}"; do
    printf 'CONFORMANCE_EXTRA_HOSTS_%s=auth.%s.%s.%s\n' \
      "$(printf '%s' "$slug" | tr 'a-z-' 'A-Z_')" "$slug" "$ORG_SLUG" "$DOMAIN"
  done
}

if [ "${1:-}" = "--write" ]; then
  OUT="$HERE/extra_hosts.env"
  { echo "# Generated by gen-extra-hosts.sh - the rig domain ($DOMAIN), family auth hosts."
    echo "# Regenerate after a domain-mode change: bash conformance/gen-extra-hosts.sh --write"
    emit
  } > "$OUT"
  echo "wrote $OUT (domain $DOMAIN)"
else
  emit
fi
